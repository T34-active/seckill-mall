USE seckill_mall;

ALTER TABLE t_user COMMENT = '用户表';
ALTER TABLE t_user
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '用户ID',
  MODIFY COLUMN username VARCHAR(64) NOT NULL COMMENT '登录用户名',
  MODIFY COLUMN password VARCHAR(100) NOT NULL COMMENT '密码(BCrypt)',
  MODIFY COLUMN role VARCHAR(32) NOT NULL COMMENT '角色: USER/ADMIN',
  MODIFY COLUMN created_at DATETIME(6) NOT NULL COMMENT '创建时间';

ALTER TABLE t_product COMMENT = '商品表';
ALTER TABLE t_product
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '商品ID',
  MODIFY COLUMN name VARCHAR(128) NOT NULL COMMENT '商品名称',
  MODIFY COLUMN price DECIMAL(10,2) NOT NULL COMMENT '售价(元)',
  MODIFY COLUMN stock INT NOT NULL COMMENT '库存快照(实时以Redis为准)',
  MODIFY COLUMN enabled BIT(1) NOT NULL COMMENT '是否上架: 1上架 0下架',
  MODIFY COLUMN created_at DATETIME(6) NOT NULL COMMENT '创建时间';

ALTER TABLE t_order COMMENT = '订单表';
ALTER TABLE t_order
  MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '订单ID',
  MODIFY COLUMN order_no VARCHAR(64) NOT NULL COMMENT '订单号',
  MODIFY COLUMN user_id BIGINT NOT NULL COMMENT '下单用户ID',
  MODIFY COLUMN product_id BIGINT NOT NULL COMMENT '商品ID',
  MODIFY COLUMN product_name VARCHAR(128) NOT NULL COMMENT '商品名称快照',
  MODIFY COLUMN quantity INT NOT NULL COMMENT '购买数量',
  MODIFY COLUMN unit_price DECIMAL(10,2) NOT NULL COMMENT '下单单价',
  MODIFY COLUMN total_amount DECIMAL(12,2) NOT NULL COMMENT '订单总金额',
  MODIFY COLUMN status VARCHAR(16) NOT NULL COMMENT '状态: CREATED/PAID/CANCELLED',
  MODIFY COLUMN created_at DATETIME(6) NOT NULL COMMENT '下单时间';
